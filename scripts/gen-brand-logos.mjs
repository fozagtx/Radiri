/**
 * Extracts the few full-colour company logos the app needs from the Iconify "logos" set (CC0,
 * gilbarbara/logos) and the Font Awesome brands set (CC BY 4.0, for Amazon) into a small module,
 * so the browser never loads the full icon sets. Run: node scripts/gen-brand-logos.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const logos = JSON.parse(readFileSync(require.resolve("@iconify-json/logos/icons.json"), "utf8"));
const fa = JSON.parse(readFileSync(require.resolve("@iconify-json/fa6-brands/icons.json"), "utf8"));

function pick(set, name) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`missing icon ${name}`);
  return { body: icon.body, width: icon.width ?? set.width ?? 16, height: icon.height ?? set.height ?? 16 };
}

const brands = {
  AAPL: { ...pick(logos, "apple"), title: "Apple", source: "logos:apple" },
  GOOGL: { ...pick(logos, "google-icon"), title: "Alphabet (Google)", source: "logos:google-icon" },
  META: { ...pick(logos, "meta-icon"), title: "Meta", source: "logos:meta-icon" },
  MSFT: { ...pick(logos, "microsoft-icon"), title: "Microsoft", source: "logos:microsoft-icon" },
  INTC: { ...pick(logos, "intel"), title: "Intel", source: "logos:intel" },
  AMZN: { ...pick(fa, "amazon"), title: "Amazon", source: "fa6-brands:amazon (CC BY 4.0)" },
};

const out = `/** Generated by scripts/gen-brand-logos.mjs. Company logos (Iconify logos set, CC0; Amazon from Font Awesome, CC BY 4.0). */
export interface BrandLogo {
  body: string;
  width: number;
  height: number;
  title: string;
  source: string;
}

export const BRAND_LOGOS: Record<string, BrandLogo> = ${JSON.stringify(brands, null, 2)};
`;
writeFileSync("src/components/app/brand-logos.ts", out);
console.log("wrote src/components/app/brand-logos.ts", Object.keys(brands).join(", "), out.length, "bytes");
